"""Regenerate the README eval section from the recorded run (replay, no key needed).

    python scripts/eval_report.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from onboard.evals import evaluate, replay_run
from onboard.llm import FIXTURES

ROOT = Path(__file__).resolve().parents[1]
START, END = "<!-- EVAL:START -->", "<!-- EVAL:END -->"


def md_table(df) -> str:
    cols = ["corruption type"] + list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for idx, row in df.iterrows():
        name = f"**{idx}**" if idx == "TOTAL" else idx
        vals = [f"**{v}**" if idx == "TOTAL" else str(v) for v in row]
        lines.append("| " + " | ".join([name] + vals) + " |")
    return "\n".join(lines)


def section(e: dict) -> str:
    m, u = e["mapping"], e["usage"]
    b, a = e["scoreboard_before"], e["scoreboard_after"]
    sb, sa = e["score_before"], e["score_after"]
    rec = sorted(json.loads(p.read_text())["recorded_at"] for p in FIXTURES.glob("*.json"))
    model = json.loads(next(FIXTURES.glob("map-*.json")).read_text())["model"]
    k = e["review_by_kind"]
    out = [
        f"Generated by `scripts/eval_report.py` from the recorded run "
        f"(`{model}`, recorded {rec[0][:10]}; replayed from `tests/fixtures/llm/`, so CI "
        f"checks these numbers without an API key).",
        "",
        "**Mapping** (LLM proposal after guards vs the hand-written "
        "[`mappings/legacy_cmms.json`](mappings/legacy_cmms.json))",
        "",
        "| | correct |",
        "|---|---|",
        f"| sheets → tables | {m['sheets_correct']} / {m['sheets_total']} |",
        f"| columns → fields | {m['columns_correct']} / {m['columns_total']} |",
        f"| code translations applied correctly | {m['codes_correct']} / {m['codes_total']} |",
        f"| code translations left for a person | {m['codes_missing']} |",
        f"| code translations applied wrongly | {m['codes_wrong']} |",
        f"| date format | {'yes' if m['date_format_correct'] else 'no'} |",
        "",
        "**What happened to each of the 2,097 injected corruptions**: *fixed* = loaded with "
        "the right value, *removed* = duplicate kept out, *held* = routed to a person, "
        "*silent* = loaded with a wrong value.",
        "",
        "Rules only:",
        "",
        md_table(b),
        "",
        f"Rules + LLM review pass ({e['review_questions']} questions: {k['date']['asked']} "
        f"dates, {k['labor']['asked']} labor, {k['dup']['asked']} duplicates; "
        f"{e['review_accepted']} answers accepted at ≥ 0.85 confidence and re-validated):",
        "",
        md_table(a),
        "",
        "| | rules only | + LLM review |",
        "|---|---|---|",
        f"| silent errors in the load | {sb['silent_errors']} | {sa['silent_errors']} |",
        f"| correct cells changed by the LLM | – | {e['silent_outside_corruptions_after']} |",
        f"| false positives (clean rows held: all from codes left for a person) | {sb['false_positives']} | {sa['false_positives']} |",
        f"| rows loaded identical to ground truth | {sb['rows_recovered']:,} / "
        f"{sb['rows_total']:,} | {sa['rows_recovered']:,} / {sa['rows_total']:,} |",
        "",
        f"**Cost per full run**: {u['calls']} calls, {u['prompt_tokens']:,} input tokens "
        f"({u['cached_tokens']:,} cached), {u['completion_tokens']:,} output + "
        f"{u['reasoning_tokens']:,} reasoning tokens, **${u['cost_usd']:.2f}** "
        f"(provider-reported). Wall time of a live run ≈ **{e['wall_s'] / 60:.0f} min** "
        f"(mapping call, then the slowest of the parallel review batches; "
        f"{u['latency_s']:.0f} s of model time in total). "
        f"Replaying the recorded responses takes seconds and needs no key.",
    ]
    return "\n".join(out)


def main() -> None:
    e = evaluate(replay_run(usage_path=None))
    text = section(e)
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "eval.md").write_text("# Eval results\n\n" + text + "\n")
    readme = ROOT / "README.md"
    r = readme.read_text()
    block = f"{START}\n{text}\n{END}"
    if START in r:
        r = re.sub(re.escape(START) + ".*?" + re.escape(END), lambda _: block, r, flags=re.S)
    else:
        r = r.replace("## From computer-use prototype to API",
                      f"## Eval results\n\n{block}\n\n## From computer-use prototype to API")
    readme.write_text(r)
    print(text)


if __name__ == "__main__":
    main()
